def _build():
    seen = set()
    for q in QUESTIONS:
        if q['id'] in seen:
            raise ValueError('معرّف سؤال مكرر: %s' % q['id'])
        seen.add(q['id'])
        if q['law'] not in LAW_TITLES:
            raise ValueError('مادة غير معروفة في السؤال %s: %s' % (q['id'], q['law']))
        if not 0 <= q['a'] < len(q['options']):
            raise ValueError('فهرس إجابة خاطئ في السؤال %s' % q['id'])
        if len(q['options']) < 2:
            raise ValueError('خيارات غير كافية في السؤال %s' % q['id'])
        q['category'] = LAW_TITLES[q['law']]


_build()

