def law_summary():
    """قائمة المواد مع عدد أسئلة كل مادة، لعرضها في صفحة المذاكرة."""
    return [{'law': n, 'title': LAW_TITLES[n],
             'count': sum(1 for q in QUESTIONS if q['law'] == n)} for n in LAWS]


def in_scope(scope):
    """أسئلة النطاق المطلوب. النطاق إما ALL_SCOPE أو عنوان مادة."""
    if not scope or scope == ALL_SCOPE:
        return list(QUESTIONS)
    return [q for q in QUESTIONS if q['category'] == scope]


def public_view(q, reveal=False):
    """صيغة السؤال المرسلة للواجهة. reveal يكشف الإجابة والشرح (وضع المذاكرة)."""
    out = {k: q[k] for k in ('id', 'law', 'category', 'topic', 'type', 'q', 'options', 'diff')}
    if reveal:
        out.update(a=q['a'], exp=q['exp'], ref=q['ref'], page=q['page'])
    return out
